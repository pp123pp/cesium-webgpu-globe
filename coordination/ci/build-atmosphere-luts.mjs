import { Buffer } from "node:buffer";
import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import { URL } from "node:url";
import encodeHalf from "../../packages/engine/Source/Scene/WebGPUAtmosphereHalf.js";
import {
  atmosphereLutKey,
  createAtmosphereParameters,
  generateAtmosphereLuts,
} from "../../packages/engine/Source/Scene/WebGPUAtmosphereModel.js";
import { createPlanetParameters } from "../../packages/engine/Source/Scene/WebGPUPlanetMath.js";

const parameters = createAtmosphereParameters();
const planet = createPlanetParameters();
const key = atmosphereLutKey(parameters, planet);
const { transmittance, multipleScattering, maxFeedback } =
  generateAtmosphereLuts(parameters, planet);

function encodeTable(table) {
  const half = encodeHalf(table.data);
  const bytes = Buffer.alloc(half.byteLength);
  for (let i = 0; i < half.length; i++) {
    bytes.writeUInt16LE(half[i], i * 2);
  }
  return bytes.toString("base64");
}

const source = `// Generated by node coordination/ci/build-atmosphere-luts.mjs.
export const defaultAtmosphereLutKey =
  ${JSON.stringify(key)};
const transmittance =
  "${encodeTable(transmittance)}";
const multipleScattering =
  "${encodeTable(multipleScattering)}";

function decodeTable(encoded, width, height) {
  const bytes = atob(encoded);
  const data = new Uint16Array(bytes.length / 2);
  for (let i = 0; i < data.length; i++) {
    data[i] = bytes.charCodeAt(i * 2) | (bytes.charCodeAt(i * 2 + 1) << 8);
  }
  return { width, height, data };
}

/** Decode the WGS84 default medium directly into RGBA16Float upload data. @private */
export default function decodeDefaultAtmosphereLuts() {
  return {
    transmittance: decodeTable(transmittance, ${transmittance.width}, ${transmittance.height}),
    multipleScattering: decodeTable(multipleScattering, ${multipleScattering.width}, ${multipleScattering.height}),
    maxFeedback: ${maxFeedback},
  };
}
`;
const output = new URL(
  "../../packages/engine/Source/Scene/WebGPUDefaultAtmosphereLuts.js",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  const current = await readFile(output, "utf8");
  if (current.replaceAll("\r\n", "\n") !== source) {
    throw new Error("Regenerate the default atmosphere LUTs with node coordination/ci/build-atmosphere-luts.mjs.");
  }
} else {
  await writeFile(output, source);
}
